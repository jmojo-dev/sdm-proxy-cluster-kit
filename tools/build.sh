#!/usr/bin/env bash
# ============================================================================
# tools/build.sh - build every artifact in dist/ from src/.
#
#   tools/build.sh                     build from this checkout
#   KIT_BASE_URL=https://x/y tools/build.sh
#
# Outputs:
#   dist/sdm-proxy-cluster-kit.sh   the single-file kit (readable; nano/vi paste target)
#   dist/paste-me.txt               one block to paste into a root shell (gzip+base64)
#   dist/install.sh                 curl | sudo bash bootstrap with the kit embedded
#   dist/SHA256SUMS                 sha256 of the three files above
#   README.md                       rendered from tools/templates/README.md.in
#
# Fails on: a TAB or CR in src/ or dist/, a line over 220 characters, a bash -n
# error, a missing mode_install/mode_debug/mode_check, or output at source time.
# Runs shellcheck when installed (warnings only).
#
# Portable to macOS bash 3.2 and Linux bash 4+: no mapfile, no associative
# arrays, no GNU-only flags (base64 -w, sed -i, readlink -f).
# ============================================================================
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"

KIT_BASE_URL=${KIT_BASE_URL:-}
KIT_BASE_URL=${KIT_BASE_URL%/}
[[ -z $KIT_BASE_URL || $KIT_BASE_URL =~ ^https://[a-zA-Z0-9./:_-]+$ ]] || { echo 'Invalid documentation URL.' >&2; exit 1; }
MAX_LINE=220
KIT_FILE=dist/sdm-proxy-cluster-kit.sh
MODES="install debug check"

say()  { printf 'build: %s\n' "$*"; }
warn() { printf 'build: WARNING: %s\n' "$*" >&2; }
die()  { printf 'build: FAILED: %s\n' "$*" >&2; exit 1; }

sha256() { # FILE -> hex digest
  local out
  if command -v sha256sum >/dev/null 2>&1; then out=$(sha256sum "$1")
  else out=$(shasum -a 256 "$1"); fi
  printf '%s' "${out%% *}"
}

[ -r VERSION ] || die "VERSION file missing"
KIT_VERSION=$(tr -d ' \r\n' < VERSION)
[[ $KIT_VERSION =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "VERSION must be a numeric major.minor.patch version"
GIT_SHA=$(git rev-parse --short HEAD 2>/dev/null || true)
if [ -n "$GIT_SHA" ] && [ -n "$(git status --porcelain -- src 2>/dev/null)" ]; then GIT_SHA="$GIT_SHA-dirty"; fi
BUILD_DATE=$(date -u +%Y-%m-%dT%H:%M:%SZ)
KIT_BUILD="built $BUILD_DATE git ${GIT_SHA:-none}"

# ---------------------------------------------------------------- inputs
SRC_FILES="src/lib/common.sh"
for f in $(find src/modes -type f -name '*.sh' | LC_ALL=C sort); do SRC_FILES="$SRC_FILES $f"; done
SRC_FILES="$SRC_FILES src/main.sh"
for f in $SRC_FILES; do [ -r "$f" ] || die "missing source file $f"; done

# ---------------------------------------------------------------- lint helpers
TAB=$(printf '\t'); CR=$(printf '\r')
check_text() { # FILE... : no TAB, no CR, no line > MAX_LINE
  local f bad=0 hits
  for f in "$@"; do
    hits=$(grep -n "$TAB" "$f" | cut -d: -f1 | head -5 | tr '\n' ' ' || true)
    if [ -n "$hits" ]; then warn "$f: TAB character on line(s) $hits(paste breaks: TAB triggers completion)"; bad=1; fi
    hits=$(grep -n "$CR" "$f" | cut -d: -f1 | head -5 | tr '\n' ' ' || true)
    if [ -n "$hits" ]; then warn "$f: CR (DOS line ending) on line(s) $hits"; bad=1; fi
    hits=$(awk -v m="$MAX_LINE" 'length($0) > m { printf "%d(%d) ", FNR, length($0) }' "$f" | head -c 200)
    if [ -n "$hits" ]; then warn "$f: line(s) longer than $MAX_LINE chars: $hits"; bad=1; fi
  done
  return $bad
}

say "kit $KIT_VERSION ($KIT_BUILD)"
SRC_ALL=$(find src -type f | LC_ALL=C sort)
# shellcheck disable=SC2086
check_text $SRC_ALL || die "src/ lint failed (see warnings above)"

# ---------------------------------------------------------------- concatenate
mkdir -p dist
rm -f dist/sdm-proxy-cluster-kit.sh dist/paste-me.txt dist/install.sh dist/SHA256SUMS
TMP=$(mktemp -d "${TMPDIR:-/tmp}/kitbuild.XXXXXX")
trap 'rm -rf "$TMP"' EXIT

{
  printf '#!/usr/bin/env bash\n'
  printf '# StrongDM Proxy Cluster Kit %s (%s)\n' "$KIT_VERSION" "$KIT_BUILD"
  printf '# GENERATED by tools/build.sh from src/ - do not edit; change src/ and rebuild.\n'
  printf '# Run as root:  bash /opt/sdm-proxy-cluster-kit/sdm-proxy-cluster-kit.sh [install|debug|check]\n'
  if [ -n "$KIT_BASE_URL" ]; then printf '# Docs: %s\n' "$KIT_BASE_URL"; fi
  # shellcheck disable=SC2016  # these lines are shell code for the kit, not for us
  printf 'case "${BASH_VERSION:-}" in\n'
  printf '  "") echo "sdm-proxy-cluster-kit: run this with bash, e.g.  bash $0" >&2; exit 2;;\n'
  printf '  [0-3].*|4.[01].*) echo "sdm-proxy-cluster-kit: needs bash 4.2+, this is $BASH_VERSION" >&2; exit 3;;\n'
  printf 'esac\n'
  printf 'KIT_VERSION="%s"\n' "$KIT_VERSION"
  printf 'KIT_BUILD="%s"\n' "$KIT_BUILD"
  for f in $SRC_FILES; do
    printf '\n# ---------------------------------------------------------------- %s\n' "$f"
    awk '1' "$f"     # awk guarantees a trailing newline on every file
  done
} > "$TMP/kit.sh"
mv -f "$TMP/kit.sh" "$KIT_FILE"
chmod 0755 "$KIT_FILE"

# ---------------------------------------------------------------- validate the kit
check_text "$KIT_FILE" || die "$KIT_FILE lint failed"
bash -n "$KIT_FILE" || die "bash -n $KIT_FILE"
for m in $MODES; do
  grep -Eq "^[[:space:]]*(function[[:space:]]+)?mode_${m}[[:space:]]*\(\)" "$KIT_FILE" \
    || die "mode function mode_$m() is not defined (expected in src/modes/$m.sh)"
done
if LC_ALL=C grep -n '[^ -~]' "$KIT_FILE" >/dev/null; then
  warn "$KIT_FILE has non-ASCII bytes (line(s) $(LC_ALL=C grep -n '[^ -~]' "$KIT_FILE" | cut -d: -f1 | head -5 | tr '\n' ' '))- may be mangled by nano/vi pastes"
fi
# Smoke test: --version must print exactly one line, proving no mode runs anything at source time.
case $(bash -c 'echo "${BASH_VERSINFO[0]}${BASH_VERSINFO[1]}"') in
  [0-3]?|4[01]) warn "local bash is older than 4.2, skipping the --version smoke test" ;;
  *)
    got=$(env -i PATH="$PATH" HOME="${HOME:-/}" NO_COLOR=1 bash "$KIT_FILE" --version </dev/null 2>&1) || die "--version exited non-zero: $got"
    [ "$got" = "sdm-proxy-cluster-kit $KIT_VERSION" ] || die "--version printed unexpected output (source-time side effects?): $got"
    ;;
esac
if command -v shellcheck >/dev/null 2>&1; then
  # SC2034 (unused variable) is noise here: common.sh is a library whose constants
  # are used by modes that may still be stubs.
  if sc=$(shellcheck -s bash -S warning -e SC2034 -f gcc "$KIT_FILE" 2>&1); then
    say "shellcheck: clean (severity >= warning)"
  else
    warn "shellcheck reported $(printf '%s\n' "$sc" | grep -c ':') finding(s) (not fatal):"
    printf '%s\n' "$sc" | head -40 | sed 's/^/  /' >&2
  fi
else
  say "shellcheck not installed - skipped"
fi

KIT_SHA256=$(sha256 "$KIT_FILE")
KIT_LINES=$(wc -l < "$KIT_FILE" | tr -d ' ')

# ---------------------------------------------------------------- template rendering
# render TEMPLATE OUT [PAYLOAD_FILE] [ENV_TABLE_FILE]
#   @@NAME@@ tokens come from R_NAME environment variables (ENVIRON: no escape processing);
#   a line that is exactly @@PAYLOAD@@ becomes PAYLOAD_FILE verbatim;
#   lines between <!-- ENV:BEGIN --> and <!-- ENV:END --> become ENV_TABLE_FILE.
render() {
  R_KIT_VERSION=$KIT_VERSION R_KIT_BUILD=$KIT_BUILD R_KIT_BASE_URL=$KIT_BASE_URL \
  R_KIT_SHA256=$KIT_SHA256 R_DELIM=${DELIM:-} R_KIT_LINES=$KIT_LINES \
  awk -v payload="${3:-}" -v envtab="${4:-}" '
    BEGIN { n = split("KIT_VERSION KIT_BUILD KIT_BASE_URL KIT_SHA256 DELIM KIT_LINES", keys, " ") }
    skip && $0 == "<!-- ENV:END -->" { skip = 0 }
    skip { next }
    $0 == "@@PAYLOAD@@" && payload != "" {
      while ((getline l < payload) > 0) print l
      close(payload); next
    }
    $0 == "<!-- ENV:BEGIN -->" && envtab != "" {
      print; print ""
      while ((getline l < envtab) > 0) print l
      close(envtab); print ""; skip = 1; next
    }
    {
      line = $0
      for (k = 1; k <= n; k++) {
        t = "@@" keys[k] "@@"; v = ENVIRON["R_" keys[k]]; out = ""
        while ((i = index(line, t)) > 0) { out = out substr(line, 1, i - 1) v; line = substr(line, i + length(t)) }
        line = out line
      }
      print line
    }' "$1" > "$2"
  if grep -n '@@[A-Z_]*@@' "$2" >/dev/null; then die "$2: unreplaced template token(s): $(grep -o '@@[A-Z_]*@@' "$2" | sort -u | tr '\n' ' ')"; fi
}

# ---------------------------------------------------------------- dist/paste-me.txt
# gzip+base64: only [A-Za-z0-9+/=] survive in the body, so TABs, '!', quotes,
# CRs and bracketed-paste quirks cannot corrupt it; sha256 catches truncation.
gzip -9 -n -c "$KIT_FILE" > "$TMP/kit.gz"
base64 < "$TMP/kit.gz" | tr -d '\r\n' | fold -w 76 > "$TMP/kit.b64"
printf '\n' >> "$TMP/kit.b64"
# Self-check the round trip with this machine's tools before shipping it.
tr -cd 'A-Za-z0-9+/=' < "$TMP/kit.b64" | base64 -d 2>/dev/null | gzip -dc > "$TMP/roundtrip.sh" \
  || die "base64/gzip round trip failed"
[ "$(sha256 "$TMP/roundtrip.sh")" = "$KIT_SHA256" ] || die "paste payload round trip is not byte-identical"
DELIM="SDMKIT_PAYLOAD_END_$(printf '%.12s' "$KIT_SHA256")"
render tools/templates/paste-me.txt.in dist/paste-me.txt "$TMP/kit.b64"
check_text dist/paste-me.txt || die "dist/paste-me.txt lint failed"
PASTE_LINES=$(wc -l < dist/paste-me.txt | tr -d ' ')
PASTE_BYTES=$(wc -c < dist/paste-me.txt | tr -d ' ')
B64_LINES=$(wc -l < "$TMP/kit.b64" | tr -d ' ')

# ---------------------------------------------------------------- dist/install.sh
# Plain-text heredoc (readable before running; no gzip/base64 needed on the host).
# The delimiter embeds the kit's own hash, and we prove the kit never contains it.
DELIM="SDMKIT_EOF_$(printf '%.20s' "$KIT_SHA256")"
if grep -qxF "$DELIM" "$KIT_FILE"; then die "kit contains the heredoc delimiter line $DELIM"; fi
render tools/templates/install.sh.in dist/install.sh "$KIT_FILE"
chmod 0755 dist/install.sh
check_text dist/install.sh || die "dist/install.sh lint failed"
bash -n dist/install.sh || die "bash -n dist/install.sh"
# The embedded copy must be byte-identical to the kit.
awk -v d="$DELIM" -v q="'" 'f && $0 == d { exit } f { print } index($0, "<<" q d q) { f = 1 }' dist/install.sh > "$TMP/embedded.sh"
[ "$(sha256 "$TMP/embedded.sh")" = "$KIT_SHA256" ] || die "kit embedded in install.sh is not byte-identical"

# ---------------------------------------------------------------- README env table
# Source lines look like:   # @env NAME  description
ENVTAB="$TMP/env.md"
# shellcheck disable=SC2086
awk '
  /^#[ ]*@env/ {
    if (!match($0, /^# @env [A-Z_][A-Z0-9_]* +[^ ]/)) {
      printf "build: WARNING: %s:%d: malformed @env line (want \"# @env NAME  description\"): %s\n", FILENAME, FNR, $0 > "/dev/stderr"
      next
    }
    name = $3; desc = $0; sub(/^# @env [A-Z_][A-Z0-9_]* +/, "", desc); gsub(/\|/, "\\|", desc)
    src = FILENAME; sub(/^.*\//, "", src); sub(/\.sh$/, "", src)
    if (!(name in d)) { d[name] = desc; where[name] = src; names[++n] = name }
    else if (index(", " where[name] ", ", ", " src ", ") == 0) where[name] = where[name] ", " src
  }
  END {
    if (n == 0) { print "_No `# @env` lines found in src/ yet._"; exit }
    for (i = 2; i <= n; i++) { k = names[i]; j = i - 1
      while (j > 0 && names[j] > k) { names[j + 1] = names[j]; j-- }
      names[j + 1] = k }
    print "| Variable | Used by | Description |"
    print "| --- | --- | --- |"
    for (i = 1; i <= n; i++) printf "| `%s` | %s | %s |\n", names[i], where[names[i]], d[names[i]]
  }' $SRC_FILES > "$ENVTAB"
ENV_COUNT=$(grep -c '^| `' "$ENVTAB" || true)

DELIM=""
render tools/templates/README.md.in README.md "" "$ENVTAB"

# ---------------------------------------------------------------- SHA256SUMS
(
  cd dist
  for f in sdm-proxy-cluster-kit.sh paste-me.txt install.sh; do printf '%s  %s\n' "$(sha256 "$f")" "$f"; done
) > dist/SHA256SUMS

# ---------------------------------------------------------------- report
say "dist/sdm-proxy-cluster-kit.sh  $KIT_LINES lines, $(wc -c < "$KIT_FILE" | tr -d ' ') bytes, sha256 $KIT_SHA256"
say "dist/paste-me.txt              $PASTE_LINES lines ($B64_LINES base64), $((PASTE_BYTES / 1024)) KB ($PASTE_BYTES bytes)"
say "dist/install.sh                $(wc -l < dist/install.sh | tr -d ' ') lines, $(( $(wc -c < dist/install.sh) / 1024 )) KB"
say "README.md                      $ENV_COUNT env var(s) documented, base URL $KIT_BASE_URL"
say "OK"
